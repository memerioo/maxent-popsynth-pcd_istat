"""
test_4_ISTAT.py
---------------
Professional testing script for the GibbsPCDSolver.
Dynamically imports mathematically reconciled marginals 
from the ISTAT data pipeline.
"""

import sys
import os
import numpy as np

# ── Path Setup ───────────────────────────────────────────────────────────────
ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT_DIR, 'src'))

from gibbs_pcd_solver import GibbsPCDSolver
from istat.preprocess_istat import build_constraint_set

# ── Data Ingestion ───────────────────────────────────────────────────────────
# We import the mathematically perfected marginals generated by our pipeline.
try:
    from istat.marginals_corrected import marginals as CLEAN_MARGINALS
except ImportError:
    print("\n❌ ERROR: Could not find 'istat/marginals_corrected.py'.")
    print("Please run the data pipeline first:")
    print("    python src/istat/preprocess_istat.py --out src/istat/marginals_corrected.py\n")
    sys.exit(1)

def run():
    print("━" * 64)
    print("  STEP 1 / 2  —  Building ConstraintSet")
    print("━" * 64)

    # Build the constraint set using the reconciled data
    cs = build_constraint_set(CLEAN_MARGINALS)

    print("\n" + "━" * 64)
    print("  STEP 2 / 2  —  GibbsPCDSolver")
    print("━" * 64)

    # Model Hyperparameters
    N_pool         = 500_000      
    n_outer        = 1100        
    n_gibbs_sweeps = 15          
    lr             = 0.005
    eps            = 1e-4   #Preventing rare-event spike
    gamma          = 0.001  # Smoothly dampens geographic contradictions
    tol            = 0.002       
    window         = 100         
    verbose_every  = 20

    print(f"Pool size       : {N_pool}")
    print(f"Outer iters     : up to {n_outer}")
    print(f"Learning rate   : {lr}")
    print(f"Gibbs sweeps/it : {n_gibbs_sweeps}\n")

    solver = GibbsPCDSolver(cs, use_numba=True)
    solver.fit(
        N_pool         = N_pool,
        n_outer        = n_outer,        
        n_gibbs_sweeps = n_gibbs_sweeps, 
        lr             = lr, 
        eps            = eps,
        gamma          = gamma,
        tol            = tol,     
        window         = window,         
        verbose_every  = verbose_every,
    )

    # ── Summary ──────────────────────────────────────────────────────────────
    print(f"\n{'─'*64}")
    print(f"  Final MRE : {solver.final_mre:.5f}")
    print(f"  Final MAE : {solver.final_mae:.5f}")
    print(f"  Iterations: {solver.n_iters}")
    print(f"  Early stop: {solver.stopped_early}")
    print(f"  Fit time  : {solver.fit_time:.1f}s")
    print(f"{'─'*64}")

    if solver.pool_ is not None:
        out_path = os.path.join(ROOT_DIR, 'experiments', f"test_4_ISTAT_pop{N_pool}.npy")
        np.save(out_path, solver.pool_)
        print(f"\n[+] Population successfully saved to: {out_path}")

    # ── Diagnostics ──────────────────────────────────────────────────────────
    print("\n" + "━" * 64)
    print("  TOP 15 UNRESOLVED CONSTRAINTS")
    print("━" * 64)
    
    from istat.attr_meta_ISTAT import ATTR_NAMES_SYNTH, ATTR_META
    alpha_hat = solver._estimate_expectations(solver.pool_)
    errors = np.abs(alpha_hat - solver.alphas)
    worst_idx = np.argsort(errors)[::-1][:15]
    
    for j in worst_idx:
        target = solver.alphas[j]
        actual = alpha_hat[j]
        diff   = errors[j]
        attrs = [ATTR_NAMES_SYNTH[a] for a in solver.cs.attrs_list[j]]
        vals  = [ATTR_META[attrs[i]]['vals'][v] for i, v in enumerate(solver.cs.vals_list[j])]
        constraint_str = ", ".join([f"{a}={v}" for a, v in zip(attrs, vals)])
        print(f"Diff: {diff:.4f}  |  Target: {target:.4f}  |  Actual: {actual:.4f}  |  {constraint_str}")

    return solver

if __name__ == "__main__":
    run()